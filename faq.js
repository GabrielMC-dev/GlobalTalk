function abrirCaixa1() {
    let rodape1 = document.getElementById('caixaP1')
    let img = document.getElementById('mudarSeta1')

    if(rodape1.style.display == 'block') {
       rodape1.style.display = 'none'
       img.textContent = "\uF181"
    }
    else {
        rodape1.style.display = 'block'
        img.textContent = "\uF182"
    }   
}
